test_that("source records preserve multiple memberships and explicit count units", {
  x<-data.frame(vertex_id=c("a","a","a","b","c"),record_id=letters[1:5],dataset=c("S1","S1","S2","S2","S3"))
  expect_equal(gflowui_source_summary(x,c("b","a")),data.frame(dataset=c("S2","S1"),vertices=c(2L,1L),records=c(2L,2L),row.names=c("S2","S1")))
  expect_identical(gflowui_source_categories(x,c("c","a","b","missing")),c("S3","Multiple source datasets","S2","Unknown source"))
  expect_identical(gflowui_source_filter(x,c("c","a","b"),"S1"),2L)
  expect_identical(gflowui_source_filter(x,c("c","a","b"),character()),1:3)
  counts<-gflowui_source_cross(x,c("a","b","c"),c("AB","AB","AC"))
  expect_equal(unname(counts["S1","AB"]),2)
  vertices<-gflowui_source_cross(x,c("a","b","c"),c("AB","AB","AC"),"vertices")
  expect_equal(unname(vertices["S1","AB"]),1)
  expect_equal(as.numeric(rowSums(gflowui_source_cross(x,c("a","b","c"),c("AB","AB","AC"),display="row"))),rep(100,3))
  expect_equal(as.numeric(colSums(gflowui_source_cross(x,c("a","b","c"),c("AB","AB","AC"),display="column"))),rep(100,2))
  x$record_id[2]<-x$record_id[1]
  expect_error(gflowui_validate_source_records(x),"unique record")
})

test_that("pair coordinates use original abundance, including zero and missing pairs", {
  a<-list(sample_ids=c("x","y","z"),taxon_names=c("A","B","C"),
    indices=list(1:3,3L,1:2),abundances=list(c(.8,.15,.05),1,c(.6,.4)))
  d<-gflowui_pair_coordinates(a,c("z","x","y","absent"),"A","B")
  expect_equal(d$t[1:2],c(.4,.15/.95));expect_equal(d$r[1:3],c(0,.05,1))
  expect_true(all(is.na(d$t[3:4])))
  expect_equal((1-d$r[1:2])*(1-d$t[1:2]),d$a[1:2])
  expect_error(gflowui_pair_coordinates(a,"x","A","A"),"distinct")
})

test_that("linked selections and dataset filters are ID based across views", {
  skip_if_not_installed("plotly")
  root<-withr::local_tempdir()
  records<-data.frame(vertex_id=c("x","x","y","z"),record_id=letters[1:4],dataset=c("S1","S2","S2","S1"))
  pairs<-data.frame(group="A → B",a="A",b="B")
  file<-file.path(root,"sources.rds");saveRDS(list(records=records,pairs=pairs),file)
  a<-list(sample_ids=c("x","y","z"),taxon_names=c("A","B","C"),
    indices=list(1:3,1:3,1:3),abundances=list(c(.8,.15,.05),c(.6,.3,.1),c(.7,.2,.1)))
  af<-file.path(root,"abundances.rds");saveRDS(a,af)
  m<-shiny::reactiveVal(list(project_id="test",metadata=list(source_datasets=list(file=file),vertex_hover=list(abundances_file=af))))
  v<-shiny::reactiveVal(list(vertex_ids=c("x","y","z"),sources=list(dcst_level2=list(values=rep("A → B",3)))))
  click<-shiny::reactiveVal(NULL)
  shiny::testServer(gflowui_source_datasets_server,args=list(manifest=m,view=v,visible=function()1:3,click3d=click,
    level=function()"dcst_level2",save_palette=function(p){mm<-m();mm$metadata$source_datasets$palette<-p;m(mm)}),{
    session$flushReact()
    session$setInputs(show=TRUE,pair="A → B")
    click(2L);session$flushReact();expect_identical(selected(),"y")
    session$setInputs(`plotly_selected-within_dcst`='[{"key":"x"},{"key":"z"}]')
    expect_setequal(selected(),c("x","z"))
    session$setInputs(add=TRUE,`plotly_click-within_dcst`='[{"key":"x"}]')
    expect_identical(selected(),"z")
    vv<-v();vv$vertex_ids<-rev(vv$vertex_ids);v(vv);session$flushReact()
    expect_identical(selected(),"z")
    session$setInputs(datasets="S2");expect_identical(groups(),"S2")
    session$setInputs(clear_datasets=1);expect_length(groups(),0)
    session$setInputs(color=list(dataset="S1",color="#123456"))
    expect_identical(unname(palette()["S1"]),"#123456")
    expect_identical(selected(),"z")
    expect_true(input$show)
    expect_true(jsonlite::validate(output$plot))
    session$setInputs(clear_points=1);expect_length(selected(),0)
  })
})
